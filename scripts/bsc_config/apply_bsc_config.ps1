<#
.SYNOPSIS
  Create the balanced-scorecard config tables in database default on the new server and load their first content
  (bsc ssas spec 6.2): runs bsc_config_ddl.sql, then bsc_config_seed.sql (generated by build_seed.py).
  A table that already has rows is not seeded again: after the first run the BI manager edits the tables with SQL.
    powershell -ExecutionPolicy Bypass -File scripts\bsc_config\apply_bsc_config.ps1 -DryRun
    powershell -ExecutionPolicy Bypass -File scripts\bsc_config\apply_bsc_config.ps1
  It asks for a ClickHouse user that may create tables and insert into database default.
#>
param(
    [string]$Url = 'http://172.22.25.214:8123/',
    [switch]$DryRun
)
$ErrorActionPreference = 'Stop'
$ddlText = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'bsc_config_ddl.sql'))
$seedText = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'bsc_config_seed.sql'))

function Split-Statements([string]$Text) {
    $body = ($Text -replace '(?m)^\s*--.*$', '')
    return @([regex]::Split($body, ';\s*\r?\n') | ForEach-Object { $_.Trim() } | Where-Object { $_ })
}

$ddl = Split-Statements $ddlText
$seed = foreach ($s in (Split-Statements $seedText)) {
    $table = ([regex]::Match($s, 'INSERT INTO default\.(\w+)')).Groups[1].Value
    if ($s -match '\)\s*VALUES\s*\r?\n') {
        $rows = ([regex]::Matches($s, '(?m)^\s{4}\(')).Count
        [pscustomobject]@{ Table = $table; Sql = $s; Rows = $rows; Label = "$rows rows" }
    } else {
        $src = ([regex]::Match($s, 'FROM (default\.\w+)')).Groups[1].Value
        [pscustomobject]@{ Table = $table; Sql = $s; Rows = -1; Label = "INSERT ... SELECT from $src" }
    }
}

foreach ($d in $ddl) { Write-Host (([regex]::Match($d, 'CREATE TABLE IF NOT EXISTS default\.\w+')).Value) }
foreach ($s in $seed) { Write-Host ("default.{0}: {1}" -f $s.Table, $s.Label) }
if ($DryRun) { Write-Host '(dry run) nothing written'; return }

$admin = Get-Credential -Message 'ClickHouse user that may create tables and insert into database default'
if (-not $admin) { throw 'No credential entered' }
$headers = @{ 'X-ClickHouse-User' = $admin.UserName.TrimStart('\'); 'X-ClickHouse-Key' = $admin.GetNetworkCredential().Password }
function Invoke-Ch([string]$Sql) {
    $body = [Text.Encoding]::UTF8.GetBytes($Sql)
    return Invoke-RestMethod -Uri $Url -Method Post -Headers $headers -Body $body -ContentType 'text/plain; charset=utf-8'
}
# Invoke-RestMethod may turn a bare number reply into an Int32, so counts are read as text.
function Get-Count([string]$Table) { return [long]([string](Invoke-Ch "SELECT count() FROM default.$Table FORMAT TabSeparated")).Trim() }

foreach ($d in $ddl) { Invoke-Ch $d | Out-Null }
$seeded = @{}
foreach ($s in $seed) {
    if (-not $seeded.ContainsKey($s.Table)) { $seeded[$s.Table] = Get-Count $s.Table }
    if ($seeded[$s.Table] -gt 0) { Write-Host "default.$($s.Table): skipped (already has $($seeded[$s.Table]) rows)"; continue }
    Invoke-Ch $s.Sql | Out-Null
    $after = Get-Count $s.Table
    if ($s.Rows -ge 0 -and $after -ne $s.Rows) { throw "default.$($s.Table): expected $($s.Rows) rows, found $after" }
    Write-Host "default.$($s.Table): loaded $after rows"
}

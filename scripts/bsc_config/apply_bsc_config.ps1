<#
.SYNOPSIS
  Create the balanced-scorecard config tables in database default on the new server and load their first content
  (bsc ssas spec 6.2): runs bsc_config_ddl.sql, then bsc_config_seed.sql (generated by build_seed.py).
  A table that already has rows is not seeded again: after the first run the BI manager edits the tables with SQL.
  -Update <file> runs the DDL (new tables only) and then every INSERT of that file, whatever the tables hold: an
  update file adds new versions of config rows (insert-only change logs), it never seeds.
    powershell -ExecutionPolicy Bypass -File scripts\bsc_config\apply_bsc_config.ps1 -DryRun
    powershell -ExecutionPolicy Bypass -File scripts\bsc_config\apply_bsc_config.ps1
    powershell -ExecutionPolicy Bypass -File scripts\bsc_config\apply_bsc_config.ps1 -Update scripts\bsc_config\bsc_config_update_2026-10-21.sql
  It asks for a ClickHouse user that may create tables and insert into database default.
#>
param(
    [string]$Url = 'http://172.22.25.214:8123/',
    [string]$Update = '',
    [switch]$DryRun
)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot '..\HnhCh.psm1') -Force
Invoke-HnhConfigApply -Ddl (Join-Path $PSScriptRoot 'bsc_config_ddl.sql') -Seed (Join-Path $PSScriptRoot 'bsc_config_seed.sql') `
    -Update $Update -Url $Url -DryRun:$DryRun

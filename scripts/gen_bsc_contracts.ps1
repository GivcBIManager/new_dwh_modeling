<#
.SYNOPSIS
  Write the dbt contracts of the bsc views from the OLD server's bsc columns (DSN chDWH, read-only), so the new views
  keep every column name, type and position (bsc spec B1). Columns a new view adds after the old ones are listed in
  $added and appended after them. Re-run when the old definitions or $added change.
    powershell -ExecutionPolicy Bypass -File scripts\gen_bsc_contracts.ps1
#>
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'HnhCh.psm1') -Force
$rows = Invoke-HnhSelect -Dsn chDWH -Sql "SELECT table, name, type FROM system.columns WHERE database = 'bsc' ORDER BY table, position"
# Columns the new views add after the old ones, by old table name: name, ClickHouse type.
$source = @('data_source', 'LowCardinality(String)')   # oasis / fusion / both, 2026-10-13
$added = @{
    'vw_work_force' = @(   # Saudization and Oracle Recruiting, 2026-10-13
        @('saudi_headcount', 'UInt64'), @('open_requisitions', 'UInt64'), @('vacant_positions', 'UInt64'),
        @('filled_positions', 'UInt64'), @('avg_time_to_fill_days', 'Nullable(Float64)'), $source)
    'vw_financial' = @(, $source)
    'vw_gl_transactions' = @(, $source)
    'vw_gl_openning_balance' = @(, $source)
    'vw_customer' = @(, $source)
    'vw_hospital_beds_utilization' = @(, $source)
    'vw_rcm' = @(, $source)
}
$lines = @('version: 2', '',
    "# Generated by scripts/gen_bsc_contracts.ps1 from the old server's bsc columns (DSN chDWH), plus the columns listed",
    '# in its $added table; do not edit by hand.',
    'models:')
$count = 0
$current = $null
function Add-Extra([string]$Table) {
    if ($Table -and $added.ContainsKey($Table)) {
        foreach ($c in $added[$Table]) {
            $script:lines += "      - name: $($c[0])", "        data_type: `"$($c[1])`""
            $script:count++
        }
    }
}
foreach ($r in $rows) {
    if ($r.table -ne $current) {
        Add-Extra $current
        $lines += "  - name: bsc_$($r.table)", '    config:', '      contract: {enforced: true}', '    columns:'
        $current = $r.table
    }
    $lines += "      - name: $($r.name)", "        data_type: `"$($r.type)`""
    $count++
}
Add-Extra $current
$out = Join-Path $PSScriptRoot '..\hnh_dwh\models\hnh\marts\bsc\_bsc__models.yml'
New-Item -ItemType Directory -Force (Split-Path -Parent $out) | Out-Null
[IO.File]::WriteAllText($out, ($lines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
Write-Host "$out`: $(@($rows | Select-Object -ExpandProperty table -Unique).Count) models, $count columns"
